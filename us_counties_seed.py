def sick_rate(state):
    base = STATE_SICK_RATES.get(state, 0.45)
    return min(0.92, max(0.10, base + random.uniform(-0.07, 0.07)))


def daily_count(pop):
    """Base daily reports per county (sick + healthy combined)."""
    return max(2, round(math.sqrt(pop / 45000)))


